/**
 * SubtitleLoader — svc_subtitles, endpoint subtitle_sidecar_fetch.
 *
 * Ports the subtitle half of VideoPlaybackResolver.resolve(): the source attaches each
 * SubtitlesStream to ExoPlayer as a SingleSampleMediaSource inside a MergingMediaSource.
 *
 * AVPlayer has no counterpart for a NETWORK sidecar: `addSubtitleFromUrl()` is documented to
 * work only after `fdSrc` is set, and our sources are always network URLs. So the sidecar is
 * fetched and parsed here, and the player screen renders the active cue over the video
 * surface. Nothing about this is a no-op — a track that cannot be fetched or parsed reports
 * why, and the caller shows that instead of silently displaying no captions.
 *
 * Formats: WebVTT and SRT are line formats; TTML/SRV3 is XML, and only its <p begin= end=>
 * cues are read (a full XML parser is not warranted for three attributes).
 */

import { BehaviorSubject } from '../rx/Rx';
import { DownloaderImpl } from '../net/Downloader';
import { Response } from '../extractor/downloader/Downloader';
import { SubtitlesStream } from '../../model/extractor/SubtitlesStream';

const TAG: string = 'SubtitleLoader';

export class SubtitleCue {
  startMs: number;
  endMs: number;
  text: string;

  constructor(startMs: number, endMs: number, text: string) {
    this.startMs = startMs;
    this.endMs = endMs;
    this.text = text;
  }
}

export class SubtitleTrack {
  languageTag: string;
  autoGenerated: boolean;
  cues: SubtitleCue[];

  constructor(languageTag: string, autoGenerated: boolean, cues: SubtitleCue[]) {
    this.languageTag = languageTag;
    this.autoGenerated = autoGenerated;
    this.cues = cues;
  }
}

export class SubtitleParser {
  /** `HH:MM:SS.mmm`, `MM:SS.mmm` and the SRT comma variant all resolve here. */
  static timestampMs(raw: string): number {
    const cleaned: string = raw.trim().replace(',', '.');
    const parts: string[] = cleaned.split(':');
    let seconds: number = 0;
    for (const part of parts) {
      const value: number = Number.parseFloat(part);
      seconds = seconds * 60 + (Number.isNaN(value) ? 0 : value);
    }
    return Math.round(seconds * 1000);
  }

  /** Strip the inline markup both WebVTT and TTML allow inside cue text. */
  static plainText(raw: string): string {
    return raw.replace(/<[^>]*>/g, '')
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&#39;/g, "'")
      .replace(/&quot;/g, '"')
      .trim();
  }

  /** WebVTT and SRT share the `start --> end` cue header, so one parser covers both. */
  static parseCueList(body: string): SubtitleCue[] {
    const cues: SubtitleCue[] = [];
    const blocks: string[] = body.replace(/\r\n/g, '\n').split('\n\n');
    for (const block of blocks) {
      const lines: string[] = block.split('\n');
      let headerIndex: number = -1;
      for (let i: number = 0; i < lines.length; i++) {
        if (lines[i].indexOf('-->') !== -1) {
          headerIndex = i;
          break;
        }
      }
      if (headerIndex < 0) {
        continue;
      }
      const header: string = lines[headerIndex];
      const arrow: number = header.indexOf('-->');
      const start: number = SubtitleParser.timestampMs(header.substring(0, arrow));
      // The end timestamp may be followed by cue settings ("align:start position:10%").
      const tail: string = header.substring(arrow + 3).trim();
      const end: number = SubtitleParser.timestampMs(tail.split(' ')[0]);
      let text: string = '';
      for (let i: number = headerIndex + 1; i < lines.length; i++) {
        text = text.length === 0 ? lines[i] : text + '\n' + lines[i];
      }
      const plain: string = SubtitleParser.plainText(text);
      if (plain.length > 0 && end > start) {
        cues.push(new SubtitleCue(start, end, plain));
      }
    }
    return cues;
  }

  /** TTML / SRV3: only `<p begin="..." end="...">text</p>` carries a cue. */
  static parseTtml(body: string): SubtitleCue[] {
    const cues: SubtitleCue[] = [];
    const pattern: RegExp = /<p[^>]*\bbegin="([^"]+)"[^>]*\bend="([^"]+)"[^>]*>([\s\S]*?)<\/p>/g;
    let match: RegExpExecArray | null = pattern.exec(body);
    while (match !== null) {
      const start: number = SubtitleParser.timestampMs(match[1].replace('s', ''));
      const end: number = SubtitleParser.timestampMs(match[2].replace('s', ''));
      const text: string = SubtitleParser.plainText(match[3].replace(/<br\s*\/?>/g, '\n'));
      if (text.length > 0 && end > start) {
        cues.push(new SubtitleCue(start, end, text));
      }
      match = pattern.exec(body);
    }
    return cues;
  }

  /** Pick the parser from the payload itself rather than trusting the declared format. */
  static parse(body: string): SubtitleCue[] {
    const head: string = body.substring(0, 400).trim();
    if (head.startsWith('<')) {
      return SubtitleParser.parseTtml(body);
    }
    return SubtitleParser.parseCueList(body);
  }
}

export class SubtitleLoader {
  private static instance: SubtitleLoader | null = null;

  private track: SubtitleTrack | null = null;
  private lastIndex: number = 0;

  /** The cue to draw right now — '' when there is none. Driven by update(). */
  readonly activeText: BehaviorSubject<string> = new BehaviorSubject<string>('');
  /** '' while healthy; the reason captions are unavailable otherwise. Never swallowed. */
  readonly lastError: BehaviorSubject<string> = new BehaviorSubject<string>('');

  static getInstance(): SubtitleLoader {
    if (SubtitleLoader.instance === null) {
      SubtitleLoader.instance = new SubtitleLoader();
    }
    return SubtitleLoader.instance;
  }

  getTrack(): SubtitleTrack | null {
    return this.track;
  }

  /**
   * endpoint subtitle_sidecar_fetch — fetch and parse one subtitle track. Torrent and
   * non-URL subtitles are skipped exactly as the source's getUrlAndNonTorrentStreams() does.
   */
  async load(subtitle: SubtitlesStream): Promise<SubtitleTrack | null> {
    this.clear();
    if (!subtitle.isUrl || subtitle.content.length === 0) {
      this.reportUnavailable('This subtitle track is not a downloadable file.');
      return null;
    }
    try {
      const response: Response = await DownloaderImpl.getInstance().get(subtitle.content);
      if (response.responseCode() < 200 || response.responseCode() >= 300) {
        this.reportUnavailable('Subtitles unavailable (HTTP ' + response.responseCode() + ').');
        return null;
      }
      const cues: SubtitleCue[] = SubtitleParser.parse(response.responseBody());
      if (cues.length === 0) {
        this.reportUnavailable('Subtitle file could not be read.');
        return null;
      }
      const track: SubtitleTrack =
        new SubtitleTrack(subtitle.getLanguageTag(), subtitle.autoGenerated, cues);
      this.track = track;
      this.lastError.onNext('');
      return track;
    } catch (e) {
      const message: string = e instanceof Error ? e.message : String(e);
      console.error(TAG + ': subtitle fetch failed: ' + message);
      this.reportUnavailable('Subtitles could not be downloaded: ' + message);
      return null;
    }
  }

  private reportUnavailable(reason: string): void {
    this.activeText.onNext('');
    this.lastError.onNext(reason);
  }

  /** Drive from the player's position stream; emits only when the cue actually changes. */
  update(positionMs: number): void {
    const cue: SubtitleCue | null = this.cueAt(positionMs);
    const text: string = cue !== null ? cue.text : '';
    if (this.activeText.getValue() !== text) {
      this.activeText.onNext(text);
    }
  }

  /**
   * Cues are in ascending order, and playback usually advances, so start from the last hit
   * and scan forward before falling back to a full scan (seeks go backwards).
   */
  cueAt(positionMs: number): SubtitleCue | null {
    const track: SubtitleTrack | null = this.track;
    if (track === null) {
      return null;
    }
    const cues: SubtitleCue[] = track.cues;
    for (let i: number = this.lastIndex; i < cues.length; i++) {
      const cue: SubtitleCue = cues[i];
      if (positionMs < cue.startMs) {
        break;
      }
      if (positionMs < cue.endMs) {
        this.lastIndex = i;
        return cue;
      }
    }
    for (let i: number = 0; i < cues.length; i++) {
      const cue: SubtitleCue = cues[i];
      if (positionMs >= cue.startMs && positionMs < cue.endMs) {
        this.lastIndex = i;
        return cue;
      }
    }
    return null;
  }

  /** Called when the track is switched off or the stream changes. */
  clear(): void {
    this.track = null;
    this.lastIndex = 0;
    this.activeText.onNext('');
    this.lastError.onNext('');
  }
}
