/*
 * Port of org.schabi.newpipe.database.playlist.model.PlaylistRemoteEntity
 * (Room entity `remote_playlists`) — a bookmarked playlist that lives on a service.
 */

import { relationalStore } from '@kit.ArkData';
import { colNumber, colNumberOrNull, colStringOrNull } from '../../../common/db/AppDatabase';
import { imageListToDbUrl } from '../../../common/image/ImageLoader';
import { LocalItemType } from '../../enums/LocalItemLocalItemType';
import { PlaylistLocalItem } from '../view/PlaylistLocalItem';
import { PlaylistInfo } from '../../extractor/PlaylistInfo';
import { Image } from '../../extractor/Image';

/** Constants.NO_SERVICE_ID */
const NO_SERVICE_ID: number = -1;

export class PlaylistRemoteEntity implements PlaylistLocalItem {
  static readonly TABLE: string = 'remote_playlists';

  /** `uid`, the autogenerated primary key. 0 until the row has been inserted. */
  uid: number = 0;
  /** `service_id` */
  serviceId: number = NO_SERVICE_ID;
  /** `name` — also the name the bookmark list orders by. */
  orderingName: string | null;
  /** `url` */
  url: string | null;
  /** `thumbnail_url` — one URL chosen by imageListToDbUrl(). */
  thumbnailUrl: string | null;
  /** `uploader` */
  uploader: string | null;
  /** `display_index` — -1 puts a newly bookmarked playlist on top. */
  displayIndex: number = -1;
  /** `stream_count` */
  streamCount: number | null;

  constructor(orderingName: string | null, url: string | null, thumbnailUrl: string | null,
    uploader: string | null, streamCount: number | null) {
    this.orderingName = orderingName;
    this.url = url;
    this.thumbnailUrl = thumbnailUrl;
    this.uploader = uploader;
    this.streamCount = streamCount;
  }

  get localItemType(): LocalItemType {
    return LocalItemType.PLAYLIST_REMOTE_ITEM;
  }

  /** Port of PlaylistRemoteEntity(PlaylistInfo). */
  static fromPlaylistInfo(info: PlaylistInfo): PlaylistRemoteEntity {
    // The source falls back to the uploader's avatars when the playlist itself has no thumbnail.
    const thumbnails: Image[] = info.thumbnails.length === 0 ? info.uploaderAvatars : info.thumbnails;
    const entity: PlaylistRemoteEntity = new PlaylistRemoteEntity(
      info.getName(),
      info.getUrl(),
      imageListToDbUrl(thumbnails),
      info.uploaderName,
      info.streamCount
    );
    entity.serviceId = info.getServiceId();
    return entity;
  }

  static fromRow(rs: relationalStore.ResultSet): PlaylistRemoteEntity {
    const entity: PlaylistRemoteEntity = new PlaylistRemoteEntity(
      colStringOrNull(rs, 'name'),
      colStringOrNull(rs, 'url'),
      colStringOrNull(rs, 'thumbnail_url'),
      colStringOrNull(rs, 'uploader'),
      colNumberOrNull(rs, 'stream_count')
    );
    entity.uid = colNumber(rs, 'uid');
    entity.serviceId = colNumber(rs, 'service_id');
    entity.displayIndex = colNumber(rs, 'display_index');
    return entity;
  }

  /** The row without `uid`, so SQLite assigns the autoincrement key on insert. */
  toValuesBucket(): relationalStore.ValuesBucket {
    const values: relationalStore.ValuesBucket = {
      'service_id': this.serviceId,
      'name': this.orderingName,
      'url': this.url,
      'thumbnail_url': this.thumbnailUrl,
      'uploader': this.uploader,
      'display_index': this.displayIndex,
      'stream_count': this.streamCount
    };
    return values;
  }

  /**
   * Port of isIdenticalTo(PlaylistInfo): false when anything the local copy caches has changed
   * upstream (name, url, track count, uploader, or the chosen thumbnail).
   */
  isIdenticalTo(info: PlaylistInfo): boolean {
    return this.serviceId === info.getServiceId() && this.streamCount === info.streamCount &&
      this.orderingName === info.getName() && this.url === info.getUrl() &&
      this.thumbnailUrl === imageListToDbUrl(info.thumbnails) &&
      this.uploader === info.uploaderName;
  }
}
