/*
 * Port of org.schabi.newpipe.database.subscription.SubscriptionEntity
 * (Room entity `subscriptions`).
 */

import { relationalStore } from '@kit.ArkData';
import { colNumber, colNumberOrNull, colStringOrNull } from '../../../common/db/AppDatabase';
import { dbUrlToImageList, imageListToDbUrl } from '../../../common/image/ImageLoader';
import { NotificationMode } from '../../enums/NotificationMode';
import { ChannelInfo } from '../../extractor/ChannelInfo';
import { ChannelInfoItem } from '../../extractor/ChannelInfoItem';

/** Constants.NO_SERVICE_ID */
const NO_SERVICE_ID: number = -1;

export class SubscriptionEntity {
  static readonly TABLE: string = 'subscriptions';

  /** `uid`, the autogenerated primary key. 0 until the row has been inserted. */
  uid: number = 0;
  /** `service_id` */
  serviceId: number = NO_SERVICE_ID;
  /** `url` */
  url: string | null = null;
  /** `name` */
  name: string | null = null;
  /** `avatar_url` — one URL chosen by imageListToDbUrl(). */
  avatarUrl: string | null = null;
  /** `subscriber_count` */
  subscriberCount: number | null = null;
  /** `description` */
  description: string | null = null;
  /** `notification_mode` */
  notificationMode: NotificationMode = NotificationMode.DISABLED;

  /** Port of SubscriptionEntity.from(ChannelInfo). */
  static fromChannelInfo(info: ChannelInfo): SubscriptionEntity {
    const entity: SubscriptionEntity = new SubscriptionEntity();
    entity.serviceId = info.getServiceId();
    entity.url = info.getUrl();
    entity.name = info.getName();
    entity.avatarUrl = imageListToDbUrl(info.avatars);
    entity.description = info.description;
    entity.subscriberCount = info.subscriberCount;
    return entity;
  }

  static fromRow(rs: relationalStore.ResultSet): SubscriptionEntity {
    const entity: SubscriptionEntity = new SubscriptionEntity();
    entity.uid = colNumber(rs, 'uid');
    entity.serviceId = colNumber(rs, 'service_id');
    entity.url = colStringOrNull(rs, 'url');
    entity.name = colStringOrNull(rs, 'name');
    entity.avatarUrl = colStringOrNull(rs, 'avatar_url');
    entity.subscriberCount = colNumberOrNull(rs, 'subscriber_count');
    entity.description = colStringOrNull(rs, 'description');
    entity.notificationMode = colNumber(rs, 'notification_mode') as NotificationMode;
    return entity;
  }

  /** The row without `uid`, so SQLite assigns the autoincrement key on insert. */
  toValuesBucket(): relationalStore.ValuesBucket {
    const values: relationalStore.ValuesBucket = {
      'service_id': this.serviceId,
      'url': this.url,
      'name': this.name,
      'avatar_url': this.avatarUrl,
      'subscriber_count': this.subscriberCount,
      'description': this.description,
      'notification_mode': this.notificationMode as number
    };
    return values;
  }

  /** Port of SubscriptionEntity.toChannelInfoItem(). */
  toChannelInfoItem(): ChannelInfoItem {
    const item: ChannelInfoItem = new ChannelInfoItem(this.serviceId,
      this.url === null ? '' : this.url, this.name === null ? '' : this.name);
    item.thumbnails = dbUrlToImageList(this.avatarUrl);
    item.subscriberCount = this.subscriberCount === null ? -1 : this.subscriberCount;
    item.description = this.description === null ? '' : this.description;
    return item;
  }
}
