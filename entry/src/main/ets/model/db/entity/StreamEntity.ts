/*
 * Port of org.schabi.newpipe.database.stream.model.StreamEntity (Room entity `streams`).
 *
 * Also carries the StreamType <-> TEXT converter (Converters.streamTypeOf / stringOf), which has no
 * module of its own in the migration plan. The Image[] <-> single-URL converter
 * (util.image.ImageStrategy) lives in common/image/ImageLoader.ts, wired to the real image-quality
 * preference; it is imported here, not duplicated.
 */

import { relationalStore } from '@kit.ArkData';
import { colBooleanOrNull, colNumber, colNumberOrNull, colString, colStringOrNull }
  from '../../../common/db/AppDatabase';
import { dbUrlToImageList, imageListToDbUrl } from '../../../common/image/ImageLoader';
import { StreamType } from '../../enums/StreamType';
import { StreamInfo } from '../../extractor/StreamInfo';
import { StreamInfoItem } from '../../extractor/StreamInfoItem';
import { PlayQueueItem } from '../../app/PlayQueueItem';

/**
 * The DB stores the StreamType by NAME (Converters.stringOf uses StreamType.name, and FeedDAO's
 * SQL compares against the literals 'LIVE_STREAM' / 'AUDIO_LIVE_STREAM'). The ported enum is
 * numeric, so the names are listed explicitly rather than derived.
 */
const STREAM_TYPE_TO_NAME: Map<StreamType, string> = new Map<StreamType, string>([
  [StreamType.NONE, 'NONE'],
  [StreamType.VIDEO_STREAM, 'VIDEO_STREAM'],
  [StreamType.AUDIO_STREAM, 'AUDIO_STREAM'],
  [StreamType.LIVE_STREAM, 'LIVE_STREAM'],
  [StreamType.AUDIO_LIVE_STREAM, 'AUDIO_LIVE_STREAM'],
  [StreamType.POST_LIVE_STREAM, 'POST_LIVE_STREAM'],
  [StreamType.POST_LIVE_AUDIO_STREAM, 'POST_LIVE_AUDIO_STREAM']
]);

const NAME_TO_STREAM_TYPE: Map<string, StreamType> = new Map<string, StreamType>([
  ['NONE', StreamType.NONE],
  ['VIDEO_STREAM', StreamType.VIDEO_STREAM],
  ['AUDIO_STREAM', StreamType.AUDIO_STREAM],
  ['LIVE_STREAM', StreamType.LIVE_STREAM],
  ['AUDIO_LIVE_STREAM', StreamType.AUDIO_LIVE_STREAM],
  ['POST_LIVE_STREAM', StreamType.POST_LIVE_STREAM],
  ['POST_LIVE_AUDIO_STREAM', StreamType.POST_LIVE_AUDIO_STREAM]
]);

/** Port of Converters.stringOf(StreamType). */
export function streamTypeToDb(streamType: StreamType): string {
  const name: string | undefined = STREAM_TYPE_TO_NAME.get(streamType);
  return name === undefined ? 'VIDEO_STREAM' : name;
}

/** Port of Converters.streamTypeOf(String). */
export function streamTypeFromDb(name: string): StreamType {
  const streamType: StreamType | undefined = NAME_TO_STREAM_TYPE.get(name);
  return streamType === undefined ? StreamType.VIDEO_STREAM : streamType;
}

/** Port of StreamTypeUtil.isLiveStream(StreamType). */
export function isLiveStreamType(streamType: StreamType): boolean {
  return streamType === StreamType.LIVE_STREAM || streamType === StreamType.AUDIO_LIVE_STREAM;
}

export class StreamEntity {
  static readonly TABLE: string = 'streams';

  /** `uid`, the autogenerated primary key. 0 until the row has been inserted. */
  uid: number = 0;
  /** `service_id` */
  serviceId: number;
  /** `url` */
  url: string;
  /** `title` */
  title: string;
  /** `stream_type` — stored as the enum member name. */
  streamType: StreamType;
  /** `duration`, in seconds. */
  duration: number;
  /** `uploader` */
  uploader: string;
  /** `uploader_url` */
  uploaderUrl: string | null = null;
  /** `thumbnail_url` — one URL chosen by imageListToDbUrl(). */
  thumbnailUrl: string | null = null;
  /** `view_count` */
  viewCount: number | null = null;
  /** `textual_upload_date` */
  textualUploadDate: string | null = null;
  /** `upload_date` — epoch milliseconds, UTC. */
  uploadDate: number | null = null;
  /** `is_upload_date_approximation` */
  isUploadDateApproximation: boolean | null = null;

  constructor(serviceId: number, url: string, title: string, streamType: StreamType,
    duration: number, uploader: string) {
    this.serviceId = serviceId;
    this.url = url;
    this.title = title;
    this.streamType = streamType;
    this.duration = duration;
    this.uploader = uploader;
  }

  /** Port of StreamEntity(StreamInfoItem). */
  static fromInfoItem(item: StreamInfoItem): StreamEntity {
    const entity: StreamEntity = new StreamEntity(item.serviceId, item.url, item.name,
      item.streamType, item.duration, item.uploaderName);
    entity.uploaderUrl = item.uploaderUrl;
    entity.thumbnailUrl = imageListToDbUrl(item.thumbnails);
    entity.viewCount = item.viewCount;
    entity.textualUploadDate = item.textualUploadDate;
    entity.uploadDate = item.uploadDate;
    entity.isUploadDateApproximation = item.isUploadDateApproximation;
    return entity;
  }

  /** Port of StreamEntity(StreamInfo). */
  static fromStreamInfo(info: StreamInfo): StreamEntity {
    const entity: StreamEntity = new StreamEntity(info.getServiceId(), info.getUrl(), info.getName(),
      info.streamType, info.duration, info.uploaderName);
    entity.uploaderUrl = info.uploaderUrl;
    entity.thumbnailUrl = imageListToDbUrl(info.thumbnails);
    entity.viewCount = info.viewCount;
    entity.textualUploadDate = info.textualUploadDate;
    entity.uploadDate = info.uploadDate;
    entity.isUploadDateApproximation = info.isUploadDateApproximation;
    return entity;
  }

  /** Port of StreamEntity(PlayQueueItem) — the queue item carries no upload date or view count. */
  static fromPlayQueueItem(item: PlayQueueItem): StreamEntity {
    const entity: StreamEntity = new StreamEntity(item.serviceId, item.url, item.title,
      item.streamType, item.duration, item.uploader);
    entity.uploaderUrl = item.uploaderUrl;
    entity.thumbnailUrl = imageListToDbUrl(item.thumbnails);
    return entity;
  }

  static fromRow(rs: relationalStore.ResultSet): StreamEntity {
    const entity: StreamEntity = new StreamEntity(
      colNumber(rs, 'service_id'),
      colString(rs, 'url'),
      colString(rs, 'title'),
      streamTypeFromDb(colString(rs, 'stream_type')),
      colNumber(rs, 'duration'),
      colString(rs, 'uploader')
    );
    entity.uid = colNumber(rs, 'uid');
    entity.uploaderUrl = colStringOrNull(rs, 'uploader_url');
    entity.thumbnailUrl = colStringOrNull(rs, 'thumbnail_url');
    entity.viewCount = colNumberOrNull(rs, 'view_count');
    entity.textualUploadDate = colStringOrNull(rs, 'textual_upload_date');
    entity.uploadDate = colNumberOrNull(rs, 'upload_date');
    entity.isUploadDateApproximation = colBooleanOrNull(rs, 'is_upload_date_approximation');
    return entity;
  }

  /** The row without `uid`, so SQLite assigns the autoincrement key on insert. */
  toValuesBucket(): relationalStore.ValuesBucket {
    const values: relationalStore.ValuesBucket = {
      'service_id': this.serviceId,
      'url': this.url,
      'title': this.title,
      'stream_type': streamTypeToDb(this.streamType),
      'duration': this.duration,
      'uploader': this.uploader,
      'uploader_url': this.uploaderUrl,
      'thumbnail_url': this.thumbnailUrl,
      'view_count': this.viewCount,
      'textual_upload_date': this.textualUploadDate,
      'upload_date': this.uploadDate,
      'is_upload_date_approximation':
        this.isUploadDateApproximation === null ? null : (this.isUploadDateApproximation ? 1 : 0)
    };
    return values;
  }

  /** Port of StreamEntity.toStreamInfoItem(). */
  toStreamInfoItem(): StreamInfoItem {
    const item: StreamInfoItem =
      new StreamInfoItem(this.serviceId, this.url, this.title, this.streamType);
    item.duration = this.duration;
    item.uploaderName = this.uploader;
    item.uploaderUrl = this.uploaderUrl;
    item.thumbnails = dbUrlToImageList(this.thumbnailUrl);
    if (this.viewCount !== null) {
      item.viewCount = this.viewCount;
    }
    item.textualUploadDate = this.textualUploadDate;
    item.uploadDate = this.uploadDate;
    item.isUploadDateApproximation =
      this.uploadDate === null ? false : (this.isUploadDateApproximation === true);
    return item;
  }
}
