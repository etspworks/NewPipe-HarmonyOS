/*
 * Port of org.schabi.newpipe.database.playlist.model.PlaylistEntity (Room entity `playlists`).
 *
 * Note that `thumbnail_url` was dropped from this table in MIGRATION_6_7: a local playlist's
 * thumbnail is the thumbnail of the stream `thumbnail_stream_id` points at, resolved by the
 * getPlaylistMetadata() query.
 */

import { relationalStore } from '@kit.ArkData';
import { colBoolean, colNumber, colStringOrNull } from '../../../common/db/AppDatabase';
import { PlaylistMetadataEntry } from '../view/PlaylistMetadataEntry';

export class PlaylistEntity {
  static readonly TABLE: string = 'playlists';

  /** The thumbnail_stream_id value meaning "this playlist has no thumbnail stream". */
  static readonly DEFAULT_THUMBNAIL_ID: number = -1;

  /** `uid`, the autogenerated primary key. 0 until the row has been inserted. */
  uid: number = 0;
  /** `name` */
  name: string | null;
  /** `is_thumbnail_permanent` — true when the user pinned the thumbnail. */
  isThumbnailPermanent: boolean;
  /** `thumbnail_stream_id` — streams(uid) of the thumbnail, or DEFAULT_THUMBNAIL_ID. */
  thumbnailStreamId: number;
  /** `display_index` — the bookmark ordering; -1 puts a new playlist on top. */
  displayIndex: number;

  constructor(name: string | null, isThumbnailPermanent: boolean, thumbnailStreamId: number,
    displayIndex: number) {
    this.name = name;
    this.isThumbnailPermanent = isThumbnailPermanent;
    this.thumbnailStreamId = thumbnailStreamId;
    this.displayIndex = displayIndex;
  }

  /** Port of PlaylistEntity(PlaylistMetadataEntry). */
  static fromMetadata(item: PlaylistMetadataEntry): PlaylistEntity {
    const entity: PlaylistEntity = new PlaylistEntity(
      item.orderingName,
      item.isThumbnailPermanent === null ? false : item.isThumbnailPermanent,
      item.thumbnailStreamId === null ? PlaylistEntity.DEFAULT_THUMBNAIL_ID
        : item.thumbnailStreamId,
      item.displayIndex === null ? -1 : item.displayIndex
    );
    entity.uid = item.uid;
    return entity;
  }

  static fromRow(rs: relationalStore.ResultSet): PlaylistEntity {
    const entity: PlaylistEntity = new PlaylistEntity(
      colStringOrNull(rs, 'name'),
      colBoolean(rs, 'is_thumbnail_permanent'),
      colNumber(rs, 'thumbnail_stream_id'),
      colNumber(rs, 'display_index')
    );
    entity.uid = colNumber(rs, 'uid');
    return entity;
  }

  /** The row without `uid`, so SQLite assigns the autoincrement key on insert. */
  toValuesBucket(): relationalStore.ValuesBucket {
    const values: relationalStore.ValuesBucket = {
      'name': this.name,
      'is_thumbnail_permanent': this.isThumbnailPermanent ? 1 : 0,
      'thumbnail_stream_id': this.thumbnailStreamId,
      'display_index': this.displayIndex
    };
    return values;
  }
}
