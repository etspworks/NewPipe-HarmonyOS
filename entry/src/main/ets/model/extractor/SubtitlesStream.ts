/*
 * Port of org.schabi.newpipe.extractor.stream.SubtitlesStream and its Builder
 * (NewPipeExtractor v0.26.5).
 *
 * java.util.Locale becomes intl.Locale (@kit.LocalizationKit), and LocaleCompat.forLanguageTag()
 * becomes its constructor, which throws on a tag it cannot parse — the same failure the source
 * turned into a ParsingException.
 *
 * KNOWN DEVIATION: Java's getDisplayLanguageName() is locale.getDisplayName(locale), one call
 * that yields "English (United Kingdom)". HarmonyOS exposes the language and the region
 * separately (i18n.System.getDisplayLanguage / getDisplayCountry), so the same string is
 * composed from the two, plus the script subtag the way Java's fallback renders it; a language
 * with neither script nor region renders as the language alone, as in Java.
 */

import { i18n, intl } from '@kit.LocalizationKit';
import { DeliveryMethod } from '../enums/DeliveryMethod';
import { MediaFormat } from '../enums/MediaFormat';
import { ItagItem } from '../../common/extractor/core/ItagItem';
import { ParsingException } from '../../common/extractor/exceptions/Exceptions';
import { Stream } from './Stream';

export class SubtitlesStream extends Stream {
  readonly format: MediaFormat | null;
  readonly locale: intl.Locale;
  readonly autoGenerated: boolean;
  readonly code: string;

  constructor(id: string, content: string, isUrl: boolean, mediaFormat: MediaFormat | null,
    deliveryMethod: DeliveryMethod, languageCode: string, autoGenerated: boolean,
    manifestUrl: string | null) {
    super(id, content, isUrl, mediaFormat, deliveryMethod, manifestUrl);
    let parsed: intl.Locale;
    try {
      parsed = new intl.Locale(languageCode);
    } catch (e) {
      throw new ParsingException('not a valid locale language code: ' + languageCode);
    }
    if (parsed.language.length === 0) {
      throw new ParsingException('not a valid locale language code: ' + languageCode);
    }
    this.locale = parsed;
    this.code = languageCode;
    this.format = mediaFormat;
    this.autoGenerated = autoGenerated;
  }

  getExtension(): string {
    return this.format === null ? '' : this.format.suffix;
  }

  isAutoGenerated(): boolean {
    return this.autoGenerated;
  }

  equalStats(cmp: Stream | null): boolean {
    if (!super.equalStats(cmp) || !(cmp instanceof SubtitlesStream)) {
      return false;
    }
    const other: SubtitlesStream = cmp as SubtitlesStream;
    return this.code === other.code && this.autoGenerated === other.autoGenerated;
  }

  getDisplayLanguageName(): string {
    const tag: string = this.code;
    const region: string = this.locale.region;
    // Both i18n calls are declared as throwing; fall back to the raw codes rather than losing
    // the whole subtitle entry over an unnamed locale.
    let language: string;
    try {
      language = i18n.System.getDisplayLanguage(this.locale.language, tag, true);
    } catch (e) {
      language = this.locale.language;
    }
    // locale.getDisplayName() qualifies the language with the SCRIPT as well as the region, which
    // is the only thing separating zh-Hans from zh-Hant: without it both captions read "中文" and
    // a tester cannot tell the two rows apart. Java has no display name for a bare script subtag
    // either and falls back to the subtag itself, which is where the reference's "中文 (HANS)"
    // comes from.
    const qualifiers: string[] = [];
    const script: string = this.locale.script;
    if (script.length !== 0) {
      qualifiers.push(script.toUpperCase());
    }
    if (region.length !== 0) {
      let country: string;
      try {
        country = i18n.System.getDisplayCountry(region, tag, true);
      } catch (e) {
        country = region;
      }
      qualifiers.push(country);
    }
    if (qualifiers.length === 0) {
      return language;
    }
    return language + ' (' + qualifiers.join(', ') + ')';
  }

  getLanguageTag(): string {
    return this.code;
  }

  getLocale(): intl.Locale {
    return this.locale;
  }

  getItagItem(): ItagItem | null {
    return null;
  }
}

export class SubtitlesStreamBuilder {
  id: string | null = null;
  content: string | null = null;
  isUrl: boolean = false;
  deliveryMethod: DeliveryMethod = DeliveryMethod.PROGRESSIVE_HTTP;
  mediaFormat: MediaFormat | null = null;
  manifestUrl: string | null = null;
  languageCode: string | null = null;
  autoGenerated: boolean | null = null;

  setId(id: string): SubtitlesStreamBuilder {
    this.id = id;
    return this;
  }

  setContent(content: string, isUrl: boolean): SubtitlesStreamBuilder {
    this.content = content;
    this.isUrl = isUrl;
    return this;
  }

  setMediaFormat(mediaFormat: MediaFormat | null): SubtitlesStreamBuilder {
    this.mediaFormat = mediaFormat;
    return this;
  }

  setDeliveryMethod(deliveryMethod: DeliveryMethod): SubtitlesStreamBuilder {
    this.deliveryMethod = deliveryMethod;
    return this;
  }

  setManifestUrl(manifestUrl: string | null): SubtitlesStreamBuilder {
    this.manifestUrl = manifestUrl;
    return this;
  }

  setLanguageCode(languageCode: string): SubtitlesStreamBuilder {
    this.languageCode = languageCode;
    return this;
  }

  setAutoGenerated(autoGenerated: boolean): SubtitlesStreamBuilder {
    this.autoGenerated = autoGenerated;
    return this;
  }

  build(): SubtitlesStream {
    if (this.content === null) {
      throw new Error('No valid content was specified. Please specify a valid one with '
        + 'setContent.');
    }
    if (this.languageCode === null) {
      throw new Error('The language code of the subtitles stream has been not set or is null. '
        + 'Make sure you specified an non null language code with setLanguageCode.');
    }
    if (this.autoGenerated === null) {
      throw new Error('The subtitles stream has been not set as an autogenerated subtitles '
        + 'stream or not. Please specify this information with setIsAutoGenerated.');
    }
    if (this.id === null) {
      this.id = this.languageCode
        + (this.mediaFormat !== null ? '.' + this.mediaFormat.suffix : '');
    }
    return new SubtitlesStream(this.id, this.content, this.isUrl, this.mediaFormat,
      this.deliveryMethod, this.languageCode, this.autoGenerated, this.manifestUrl);
  }
}
