/*
 * Port of app/src/main/java/us/shandian/giga/get/DownloadMission.java - the state of one
 * pending download.
 *
 * What moved and why:
 *   - The Java class owned BOTH the state and the worker threads (DownloadRunnable,
 *     DownloadInitializer, DownloadMissionRecover, the mHandler notify() calls). ArkTS has no
 *     threads: the transfer loop and the recovery pass live in common/download/DownloadManager.ts
 *     and report progress on an Observable (phase2-logic-contract.md section 1). This class keeps
 *     exactly the state the source persisted plus the predicates that read it, so
 *     `isFinished/isCorrupt/isPsRunning/...` still decide the same things.
 *   - `psAlgorithm` (Postprocessing) is persisted by NAME (`psName` + `psArgs`), not as a
 *     serialized object: common/download/postprocessing/Postprocessing.ts maps the name onto the
 *     muxer, the same table Postprocessing.getAlgorithm() is. Every algorithm the source ships
 *     works on the mission's own file, so `psWorksOnSameFile` follows `hasPsAlgorithm`.
 *   - `blocks` / `blockAcquired` / `fallbackResumeOffset` drove the multi-threaded block
 *     allocator. The port downloads one range at a time and resumes from `done`, so only the
 *     resume offset is state; `blocks` is kept as the "is this mission initialized" marker the
 *     source uses it for (isInitialized() == blocks != null).
 */

