export const ERROR_NOTHING: number = -1;
export const ERROR_PATH_CREATION: number = 1000;
export const ERROR_FILE_CREATION: number = 1001;
export const ERROR_UNKNOWN_EXCEPTION: number = 1002;
export const ERROR_PERMISSION_DENIED: number = 1003;
export const ERROR_SSL_EXCEPTION: number = 1004;
export const ERROR_UNKNOWN_HOST: number = 1005;
export const ERROR_CONNECT_HOST: number = 1006;
export const ERROR_POSTPROCESSING: number = 1007;
export const ERROR_POSTPROCESSING_STOPPED: number = 1008;
export const ERROR_POSTPROCESSING_HOLD: number = 1009;
export const ERROR_INSUFFICIENT_STORAGE: number = 1010;
export const ERROR_PROGRESS_LOST: number = 1011;
export const ERROR_TIMEOUT: number = 1012;
export const ERROR_RESOURCE_GONE: number = 1013;
export const ERROR_HTTP_NO_CONTENT: number = 204;
export const ERROR_HTTP_FORBIDDEN: number = 403;

/** DownloadMission.BUFFER_SIZE / BLOCK_SIZE, verbatim. */
export const BUFFER_SIZE: number = 64 * 1024;
export const BLOCK_SIZE: number = 512 * 1024;

/**
 * Port of MissionRecoveryInfo: what DownloadMissionRecover needs to find the SAME stream again in
 * a fresh extraction of `mission.source` once its url stopped working (YouTube answers 403 when
 * the url's `expire=` has passed). Persisted inside the mission's JSON, so plain fields only.
 * `validateCondition` (ETag / Last-Modified) is not kept: the port compares the resource length.
 */
export class MissionRecoveryInfo {
  /** Stream.getFormatId(): the source compares the MediaFormat itself. */
  formatId: number = -1;
  /** 'a' audio, 'v' video, 's' subtitles. */
  kind: string = '';
  /** Video: the resolution. Subtitles: the language tag. */
  desired: string = '';
  /** Video: video-only. Subtitles: auto-generated. */
  desired2: boolean = false;
  /** Audio: the average bitrate. */
  desiredBitrate: number = 0;

  /** The source's MissionRecoveryInfo(Stream) constructor. */
  static of(stream: Stream): MissionRecoveryInfo {
    const info: MissionRecoveryInfo = new MissionRecoveryInfo();
    info.formatId = stream.getFormatId();
    if (stream instanceof AudioStream) {
      info.kind = 'a';
      info.desiredBitrate = (stream as AudioStream).getAverageBitrate();
    } else if (stream instanceof VideoStream) {
      const video: VideoStream = stream as VideoStream;
      info.kind = 'v';
      info.desired = video.getResolution();
      info.desired2 = video.getIsVideoOnly();
    } else if (stream instanceof SubtitlesStream) {
      const subtitles: SubtitlesStream = stream as SubtitlesStream;
      info.kind = 's';
      info.desired = subtitles.getLanguageTag();
      info.desired2 = subtitles.isAutoGenerated();
    }
    return info;
  }
}

/** The persisted JSON record of a pending mission. */
export interface DownloadMissionJson extends MissionJson {
  urls: string[];
  done: number;
  unknownLength: boolean;
  offsets: number[];
  psState: number;
  current: number;
  nearLength: number;
  threadCount: number;
  enqueued: boolean;
  errCode: number;
  initialized: boolean;
  recoveryInfo: MissionRecoveryInfo[];
  /** Absent in records written before post-processing was ported. */
  psName?: string;
  psArgs?: string[];
  psStreamInfo?: string[];
}

export class DownloadMission extends Mission {
  /** The urls of the file to download. */
  urls: string[] = [];

  /** Number of bytes downloaded and written. */
  done: number = 0;

  /** Indicates a file generated dynamically on the web server. */
  unknownLength: boolean = false;

  /** Offset in the file where the data should be written, one per url. */
  offsets: number[] = [];

  /** Post-processing state: 0 ready, 1 running, 2 completed, 3 hold. */
  psState: number = 0;

  /** Whether a post-processing algorithm was attached. */
  hasPsAlgorithm: boolean = false;

  /** Whether the post-processing algorithm rewrites the download file in place. */
  psWorksOnSameFile: boolean = false;

  /** Postprocessing.ALGORITHM_*, or '' for none. */
  psName: string = '';

  /** The algorithm's arguments (getArgumentAt). */
  psArgs: string[] = [];

  /**
   * Postprocessing.streamInfo, the part the Opus tags read: [url, category, uploader, name,
   * upload date in epoch ms or ''].
   */
  psStreamInfo: string[] = [];

  /** The current resource to download: `urls[current]` and `offsets[current]`. */
  current: number = 0;

  /** `transient` in the source: path of the JSON file this mission is persisted in. */
  metadata: string = '';

  /** `transient` in the source: maximum attempts, from the downloads_max_retry preference. */
  maxRetry: number = 3;

  /** Approximated final length: the sum of all resource sizes. */
  nearLength: number = 0;

  /** Maximum of download threads running, chosen by the user. */
  threadCount: number = 3;

  /** Information required to recover a download whose urls expired. */
  recoveryInfo: MissionRecoveryInfo[] = [];

  /** `transient` in the source: whether the transfer loop is currently running. */
  running: boolean = false;

  enqueued: boolean = true;

  errCode: number = ERROR_NOTHING;
  errObject: Error | null = null;

  /**
   * The source's `blocks != null` marker: set once the initializer has resolved the resource
   * length and the file has been created.
   */
  initialized: boolean = false;

  /** Port of the public constructor. */
  static create(urls: string[], storage: StoredFile, kind: string): DownloadMission {
    if (urls.length < 1) {
      throw new Error('urls array is empty');
    }
    const mission: DownloadMission = new DownloadMission();
    mission.urls = urls;
    mission.kind = kind;
    const offsets: number[] = [];
    for (let i: number = 0; i < urls.length; i++) {
      offsets.push(0);
    }
    mission.offsets = offsets;
    mission.enqueued = true;
    mission.maxRetry = 3;
    mission.storage = storage;
    mission.source = urls[0];
    return mission;
  }

  /** The psName/psArgs half of the source's constructor. */
  setPostprocessing(name: string, args: string[]): void {
    this.psName = name;
    this.psArgs = args;
    this.hasPsAlgorithm = name.length > 0;
    this.psWorksOnSameFile = this.hasPsAlgorithm;
  }

  /** Port of isFinished(). */
  isFinished(): boolean {
    return this.current >= this.urls.length && (!this.hasPsAlgorithm || this.psState === 2);
  }

  /** Port of isPsFailed(). */
  isPsFailed(): boolean {
    if (this.errCode === ERROR_POSTPROCESSING || this.errCode === ERROR_POSTPROCESSING_STOPPED) {
      return this.psWorksOnSameFile;
    }
    return false;
  }

  /** Port of isPsRunning(). */
  isPsRunning(): boolean {
    return this.hasPsAlgorithm && (this.psState === 1 || this.psState === 3);
  }

  /** Port of isInitialized(). */
  isInitialized(): boolean {
    return this.initialized;
  }

  /**
   * Port of hasInvalidStorage().
   *
   * "Invalid" is only ever concluded for a handle that can be verified in THIS process, the same
   * rule DownloadManager.loadFinishedMissions() already applies: the picker's grant dies with the
   * process, so after a restart existsAsFile() was false for every mission the user had ever
   * confirmed - the file sitting untouched on disk. Every restored row then took the
   * invalid-storage branch, which reads 0 B and whose Retry re-opens the save picker instead of
   * resuming. The reference, whose takePersistableUriPermission keeps the handle alive, offers
   * that row its ordinary Start / Enqueue menu.
   */
  hasInvalidStorage(): boolean {
    const file: StoredFile | null = this.storage;
    if (file === null) {
      return true;
    }
    return file.isVerifiable() && !file.existsAsFile();
  }

  /** Port of isCorrupt(). */
  isCorrupt(): boolean {
    if (this.urls.length < 1) {
      return false;
    }
    return this.isPsFailed() || this.errCode === ERROR_POSTPROCESSING_HOLD || this.isFinished();
  }

  /** Port of getLength(): the approximated final length of the file. */
  getLength(): number {
    if (this.psState === 1 || this.psState === 3) {
      return this.length;
    }
    const index: number = this.current < this.offsets.length
      ? this.current
      : this.offsets.length - 1;
    const base: number = this.offsets.length === 0 ? 0 : this.offsets[index];
    const first: number = this.offsets.length === 0 ? 0 : this.offsets[0];
    const calculated: number = base + this.length - first;
    return Math.max(calculated, this.nearLength);
  }

  /** Port of setEnqueued(boolean). Persisting is the DownloadManager's job here. */
  setEnqueued(queue: boolean): void {
    this.enqueued = queue;
  }

  /** Port of resetState(rollback, persistChanges, errorCode); persisting is the caller's job. */
  resetState(rollback: boolean, errorCode: number): void {
    this.length = 0;
    this.errCode = errorCode;
    this.errObject = null;
    this.unknownLength = false;
    this.initialized = false;
    this.done = 0;
    if (rollback) {
      this.current = 0;
    }
  }

  /** The current url, or null when the mission has run past its last resource. */
  currentUrl(): string | null {
    if (this.current < 0 || this.current >= this.urls.length) {
      return null;
    }
    return this.urls[this.current];
  }

  toJson(): DownloadMissionJson {
    const out: DownloadMissionJson = {
      source: '', length: 0, timestamp: 0, kind: '',
      storageUri: '', storageName: '', storageType: '', storageTag: '', storageTree: '',
      urls: this.urls,
      done: this.done,
      unknownLength: this.unknownLength,
      offsets: this.offsets,
      psState: this.psState,
      current: this.current,
      nearLength: this.nearLength,
      threadCount: this.threadCount,
      enqueued: this.enqueued,
      errCode: this.errCode,
      initialized: this.initialized,
      recoveryInfo: this.recoveryInfo,
      psName: this.psName,
      psArgs: this.psArgs,
      psStreamInfo: this.psStreamInfo
    };
    this.writeMissionJson(out);
    return out;
  }

  static fromJson(raw: DownloadMissionJson): DownloadMission {
    const mission: DownloadMission = new DownloadMission();
    mission.readMissionJson(raw);
    mission.urls = raw.urls;
    mission.done = raw.done;
    mission.unknownLength = raw.unknownLength;
    mission.offsets = raw.offsets;
    mission.psState = raw.psState;
    mission.current = raw.current;
    mission.nearLength = raw.nearLength;
    mission.threadCount = raw.threadCount;
    mission.enqueued = raw.enqueued;
    mission.errCode = raw.errCode;
    mission.initialized = raw.initialized;
    mission.recoveryInfo = raw.recoveryInfo;
    const psName: string | undefined = raw.psName;
    const psArgs: string[] | undefined = raw.psArgs;
    mission.setPostprocessing(psName === undefined ? '' : psName,
      psArgs === undefined ? [] : psArgs);
    const psStreamInfo: string[] | undefined = raw.psStreamInfo;
    mission.psStreamInfo = psStreamInfo === undefined ? [] : psStreamInfo;
    return mission;
  }
}
